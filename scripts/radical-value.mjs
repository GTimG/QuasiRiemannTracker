// Every expression in the existing square-root grammar is a rational linear
// combination of square roots of positive integers. Terms in distinct square
// classes are linearly independent over Q, so an empty sum is exactly zero.
import { parseRadicalExpression } from "../core/exact-bound.mjs";
import { gcd } from "../core/rational.mjs";

const integer = (n) => ({
  terms: n ? new Map([[1n, n]]) : new Map(),
  denominator: 1n,
});

function floorSqrt(n) {
  if (n < 2n) return n;
  let x = 1n << BigInt(Math.ceil(n.toString(2).length / 2));
  for (;;) {
    const next = (x + n / x) / 2n;
    if (next >= x) return x;
    x = next;
  }
}

// Combine equivalent square classes without factoring large radicands.
// For example, sqrt(12) and sqrt(27) contribute 2 and 3 copies of sqrt(3).
function addTerm(terms, radicand, coefficient) {
  if (!coefficient) return;
  if (terms.has(radicand)) {
    const total = terms.get(radicand) + coefficient;
    if (total) terms.set(radicand, total);
    else terms.delete(radicand);
    return;
  }
  for (const [other, previous] of terms) {
    const common = gcd(other, radicand);
    const a = other / common,
      b = radicand / common;
    const x = floorSqrt(a),
      y = floorSqrt(b);
    if (x * x !== a || y * y !== b) continue;
    terms.delete(other);
    radicand = common;
    coefficient = previous * x + coefficient * y;
    break;
  }
  if (coefficient) terms.set(radicand, coefficient);
}

function add(a, b, sign = 1n) {
  const denominator =
    (a.denominator / gcd(a.denominator, b.denominator)) * b.denominator;
  const terms = new Map();
  for (const [r, c] of a.terms) terms.set(r, c * (denominator / a.denominator));
  for (const [r, c] of b.terms)
    addTerm(terms, r, sign * c * (denominator / b.denominator));
  return { terms, denominator };
}

function multiply(a, b) {
  const terms = new Map();
  for (const [r, c] of a.terms)
    for (const [s, e] of b.terms) {
      const g = gcd(r, s);
      addTerm(terms, (r / g) * (s / g), c * e * g);
    }
  return { terms, denominator: a.denominator * b.denominator };
}

function evaluate(node) {
  switch (node.kind) {
    case "int":
      return integer(BigInt(node.value));
    case "sqrt":
      return {
        terms: new Map([[BigInt(node.radicand.value), 1n]]),
        denominator: 1n,
      };
    case "+":
      return add(evaluate(node.left), evaluate(node.right));
    case "-":
      return add(evaluate(node.left), evaluate(node.right), -1n);
    case "*":
      return multiply(evaluate(node.left), evaluate(node.right));
    case "/": {
      const a = evaluate(node.left);
      return { ...a, denominator: a.denominator * BigInt(node.right.value) };
    }
    default:
      throw Error("Unsupported radical operator");
  }
}

export const radicalValue = (label) => evaluate(parseRadicalExpression(label));
export const rationalValue = (r) => ({
  ...integer(BigInt(r.numerator)),
  denominator: BigInt(r.denominator),
});
export const equalValues = (a, b) => !add(a, b, -1n).terms.size;

// After the exact zero test, refining rational enclosures must eventually
// determine the sign. The denominator is positive throughout the grammar.
function compare(a, b) {
  const { terms } = add(a, b, -1n);
  if (!terms.size) return 0;
  for (let bits = 16n; ; bits *= 2n) {
    let lo = 0n,
      hi = 0n;
    for (const [r, c] of terms) {
      const scaled = r << (2n * bits);
      const l = floorSqrt(scaled),
        h = l * l === scaled ? l : l + 1n;
      lo += c * (c > 0n ? l : h);
      hi += c * (c > 0n ? h : l);
    }
    if (lo > 0n) return 1;
    if (hi < 0n) return -1;
  }
}

// The conjugates of a sum of distinct square classes are its consistent sign
// changes. Their number is the size of the group generated by those classes:
// a sign change fixes the sum exactly when it fixes every nonzero term.
// If its degree exceeds that of p, skip the potentially expensive p(value).
function degreeExceeds(terms, degree) {
  if (terms.size > degree) return true;
  const classes = [1n];
  for (const r of terms.keys()) {
    if (
      classes.some((s) => {
        const g = gcd(r, s);
        const ratio = (r / g) * (s / g);
        const t = floorSqrt(ratio);
        return t * t === ratio;
      })
    )
      continue;
    if (classes.length * 2 > degree) return true;
    const products = classes.map((s) => {
      const g = gcd(r, s);
      return (r / g) * (s / g);
    });
    classes.push(...products);
  }
  return false;
}

export function rootEqualsRadical(root, value) {
  if (degreeExceeds(value.terms, root.coefficients.length - 1)) return false;
  if (
    compare(value, rationalValue(root.lower)) <= 0 ||
    compare(value, rationalValue(root.upper)) >= 0
  )
    return false;
  let sum = integer(0n);
  for (let i = root.coefficients.length - 1; i >= 0; i--)
    sum = add(multiply(sum, value), integer(root.coefficients[i]));
  return !sum.terms.size;
}
